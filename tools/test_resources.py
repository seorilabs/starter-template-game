import json
import unittest
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
class ResourceTests(unittest.TestCase):
    def test_adoption_never_requires_generated_metadata(self):
        profile = json.loads((ROOT/'godot/data/outgame/outgame-profile.json').read_text())
        generated = [name for name in profile['uiStandard']['resources'] if Path(name).suffix in ('.uid','.import')]
        self.assertEqual([], generated, 'fresh clones must not need metadata generated by an earlier import')
if __name__ == '__main__': unittest.main()
